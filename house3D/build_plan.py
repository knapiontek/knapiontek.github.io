def cm(f, r):  # inclusive pixel rect -> [x1,z1,x2,z2] cm
    x1,y1,x2,y2 = r
    return [round((x1-f['x0'])*f['s'],1), round((y1-f['y0'])*f['s'],1), round((x2+1-f['x0'])*f['s'],1), round((y2+1-f['y0'])*f['s'],1)]

