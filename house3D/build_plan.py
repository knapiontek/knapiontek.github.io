def conv(f, d):
    o = {"walls":[{"r":cm(f,r),"kind":k} for r,k in d["walls"]],
         "openings":[{"r":cm(f,r),"sill":s,"head":h,"kind":k} for r,s,h,k in d["openings"]],
         "rooms":[]}
    for name,area,rects,mat in d["rooms"]:
        rs=[cm(f,r) for r in rects]
        a=sum((r[2]-r[0])*(r[3]-r[1]) for r in rs)/1e4
        o["rooms"].append({"name":name,"planArea":round(area,2),"rects":rs,"material":mat})
        print(f"{name:28s} plan {area:6.2f}  model {a:6.2f}")
    for k in ("fireplace","stair","void"):
        if k in d: o[k]=cm(f,d[k])
    return o
